// One command to get a working local genzen. Nothing starts and nothing is
// installed: local dev points at the same Neon database and Blob store the
// deployment uses, inside one Vercel project (#777). This script logs you in,
// links or creates the project, provisions the store and the database when
// they are missing, pulls the project's variables, applies migrations, makes
// sure you have a login, asks for any provider key still missing, and starts
// the dev server. Idempotent -- run it as often as you like.
//
// **The rule: every run stops at the first missing thing, says the one line
// that fixes it, and exits -- or fixes it itself when it can.** No checklist
// up front. The person who reads ahead gets nothing from this script, and the
// person who does not is never behind.
//
// Prerequisites are pnpm and the Vercel CLI. There is no Docker and no global
// service to run.
//
//   pnpm local:up            set up, then run the dev server
//   pnpm local:up --no-dev   set up only; don't start the dev server
//
// The only values you have to supply are your provider keys (FAL, then
// Anthropic). They are stored on the Vercel project, so the deployment and
// every Mac share them, and this script asks for each one the project does
// not already have. Everything else -- the database, the store, the session
// secret -- is made on the project the first time it is missing. There is
// deliberately no `.env.local.example`: a template listing a dozen vars reads
// as "this needs configuring" when it does not.
import { spawn, spawnSync } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createInterface } from 'node:readline/promises'
import { connect } from 'node:net'

const ROOT = new URL('../', import.meta.url)
const ENV_LOCAL = new URL('.env.local', ROOT)
const ENV_PULLED = new URL('.env.vercel-pull', ROOT)
const SKIP_DEV = process.argv.includes('--no-dev')
/** Mirrors the `dev` script in package.json. */
const DEV_PORT = 3000
const DEV_URL = `http://localhost:${DEV_PORT}/`
const ENVIRONMENTS = 'production,preview,development'

/**
 * The local login. These live in `.env.local` so the credentials are yours to
 * change: edit them, re-run `local:up`, and the password is re-synced -- that is
 * the whole password-reset story, with no way for the file and the database to
 * disagree. They are local-only lines in a file the Vercel pull otherwise owns,
 * which is why the pull lands in a scratch file and is merged in.
 *
 * The password is **generated**, not a constant, and the address is a reserved
 * domain. A checked-in default would be a real credential published in a public
 * repo. Generating per-clone also means two machines never share a local login
 * -- though they do share the database, so the second Mac's run adds a second
 * user rather than a second password.
 */
const DEV_USER_DEFAULTS = {
  LOCAL_DEV_EMAIL: 'dev@example.com',
  LOCAL_DEV_PASSWORD: randomBytes(9).toString('base64url'),
}

const ENV_HEADER = `# Generated by \`pnpm local:up\`. Everything except LOCAL_DEV_* comes from the
# Vercel project and is overwritten on every run -- change it there, not here.
`

function run(command, args, { capture = false } = {}) {
  const result = spawnSync(command, args, {
    cwd: ROOT,
    stdio: capture ? 'pipe' : 'inherit',
    encoding: 'utf8',
  })
  if (result.status !== 0) {
    if (capture && result.stderr) process.stderr.write(result.stderr)
    console.error(`\nFailed: ${command} ${args.join(' ')}`)
    process.exit(result.status ?? 1)
  }
  return result.stdout ?? ''
}

/** Replace in place when present, append when not -- comments and order survive. */
function upsert(text, key, value) {
  const line = `${key}=${value}`
  const pattern = new RegExp(`^${key}=.*$`, 'm')
  return pattern.test(text)
    ? text.replace(pattern, line)
    : `${text.replace(/\s*$/, '')}\n${line}\n`
}

function read(key, text) {
  return (text.match(new RegExp(`^${key}=(.*)$`, 'm')) ?? [])[1]?.trim()
}

/** `vercel env pull` quotes values; `.env.local` readers take them either way. */
function unquote(value) {
  return value.replace(/^"(.*)"$/, '$1')
}

/** Is anything listening on this host:port? A plain TCP probe -- no HTTP. */
function hostPortInUse(host, port) {
  return new Promise((resolve) => {
    const socket = connect({ port, host })
    const settle = (result) => {
      socket.destroy()
      resolve(result)
    }
    socket.setTimeout(500)
    socket.once('connect', () => settle(true))
    socket.once('timeout', () => settle(false))
    socket.once('error', () => settle(false))
  })
}

/**
 * The dev server binds `localhost`, which resolves to ::1 before 127.0.0.1 on
 * macOS -- so probing only IPv4 can miss a server that is very much running,
 * and we'd start a second one. Check both.
 */
async function portInUse(port) {
  const results = await Promise.all([
    hostPortInUse('127.0.0.1', port),
    hostPortInUse('::1', port),
  ])
  return results.some(Boolean)
}

function openBrowser(url) {
  const opener =
    process.platform === 'darwin'
      ? ['open', [url]]
      : process.platform === 'win32'
        ? ['cmd', ['/c', 'start', '', url]]
        : ['xdg-open', [url]]
  spawnSync(opener[0], opener[1], { stdio: 'ignore' })
}

// 1. Preflight. The CLI is the one thing this script cannot install for you;
//    login is a browser round trip it can start but not finish.
if (spawnSync('vercel', ['--version'], { stdio: 'ignore' }).status !== 0) {
  console.error(
    'The Vercel CLI is not installed. `pnpm add -g vercel`, then re-run.',
  )
  process.exit(1)
}
if (spawnSync('vercel', ['whoami'], { stdio: 'ignore' }).status !== 0) {
  console.log('\n> not logged in to Vercel -- opening the login')
  run('vercel', ['login'])
}
// The CLI writes `project.json` for a plain link and `repo.json` when the
// project is connected to this repository's remote; either one means linked.
// Neither means a fresh clone, or a fresh account -- `--yes` links the project
// named after this folder, creating it when there is none.
const linked = ['.vercel/project.json', '.vercel/repo.json'].some((file) =>
  existsSync(new URL(file, ROOT)),
)
if (!linked) {
  console.log('\n> linking this clone to the Vercel project')
  run('vercel', ['link', '--yes'])
}

// 2. The project's variables. Pulled into a scratch file and merged, because
//    `vercel env pull` replaces its target outright and the dev login below
//    lives only in `.env.local`.
function pullEnv() {
  run('vercel', [
    'env',
    'pull',
    '.env.vercel-pull',
    '--environment',
    'development',
    '--yes',
  ])
  const pulled = readFileSync(ENV_PULLED, 'utf8')
  rmSync(ENV_PULLED)
  let text = existsSync(ENV_LOCAL)
    ? readFileSync(ENV_LOCAL, 'utf8')
    : ENV_HEADER
  for (const line of pulled.split('\n')) {
    const separator = line.indexOf('=')
    if (separator === -1 || line.trimStart().startsWith('#')) continue
    const key = line.slice(0, separator).trim()
    text = upsert(text, key, unquote(line.slice(separator + 1).trim()))
  }
  return text
}
console.log('\n> pulling project variables from Vercel')
let env = pullEnv()

// 3. The store and the database, made when missing. Both are one CLI command
//    with no questions: a private Blob store connected to every environment,
//    and a Neon database through the marketplace on its free plan. You never
//    hear the words Blob or Neon unless one of these fails.
let provisioned = false
if (!read('BLOB_READ_WRITE_TOKEN', env)) {
  console.log('\n> no image store on the project yet -- creating one')
  run('vercel', [
    'blob',
    'create-store',
    'genzen-images',
    '--access',
    'private',
    '--yes',
  ])
  provisioned = true
}
if (!read('DATABASE_URL', env)) {
  console.log(
    '\n> no database on the project yet -- creating one (about a minute)',
  )
  run('vercel', [
    'integration',
    'add',
    'neon',
    '--no-claim',
    '--non-interactive',
  ])
  provisioned = true
}
if (provisioned) {
  console.log('\n> pulling project variables again')
  env = pullEnv()
}
for (const key of ['DATABASE_URL', 'BLOB_READ_WRITE_TOKEN']) {
  if (!read(key, env)) {
    console.error(
      `\n${key} is still not on the Vercel project after provisioning. Check the project's Storage tab and re-run.`,
    )
    process.exit(1)
  }
}
if (!read('AUTH_SESSION_SECRET', env)) {
  // Generated once, on the project, so every environment signs the same cookie
  // and nobody ever has to see it.
  console.log('\n> generating AUTH_SESSION_SECRET on the project')
  run('vercel', [
    'env',
    'add',
    'AUTH_SESSION_SECRET',
    '--environment',
    ENVIRONMENTS,
    '--sensitive',
    '--value',
    randomBytes(32).toString('hex'),
  ])
  env = pullEnv()
}

// The login is asked for once, on the first run, with the generated values
// as the defaults so Enter alone is fine. After that the lines in `.env.local`
// are the answer and a re-run never asks. Non-interactive runs (CI, a pipe)
// take the defaults.
if (!read('LOCAL_DEV_EMAIL', env) && !read('LOCAL_DEV_PASSWORD', env)) {
  if (process.stdin.isTTY) {
    console.log(`
Your login. This is the user you sign in as, locally and on the deployment;
it lands in .env.local, and editing it there and re-running changes it.`)
    const rl = createInterface({ input: process.stdin, output: process.stdout })
    const email = (
      await rl.question(`Email [${DEV_USER_DEFAULTS.LOCAL_DEV_EMAIL}]: `)
    ).trim()
    let password = ''
    for (;;) {
      password = (
        await rl.question(
          `Password [${DEV_USER_DEFAULTS.LOCAL_DEV_PASSWORD}]: `,
        )
      ).trim()
      // The same floor `pnpm users add` holds.
      if (!password || password.length >= 6) break
      console.log('At least 6 characters.')
    }
    rl.close()
    if (email) DEV_USER_DEFAULTS.LOCAL_DEV_EMAIL = email
    if (password) DEV_USER_DEFAULTS.LOCAL_DEV_PASSWORD = password
  }
}
// Seeded only when absent, so an edited login survives a re-run.
for (const [key, value] of Object.entries(DEV_USER_DEFAULTS)) {
  if (!read(key, env)) env = upsert(env, key, value)
}
writeFileSync(ENV_LOCAL, env)
console.log('.env.local: synced from the project')

// 4. Schema. `scripts/migrate.mjs` only applies files not already recorded in
//    `schema_migrations`, so re-running it against a database you have been
//    working in is a no-op rather than a risk.
console.log('\n> migrating the database')
run('node', ['scripts/migrate.mjs'])

// 5. The dev login. Provisioning is the whole whitelist -- a fresh database has
//    no way in without it. The password is re-synced on every run rather than
//    skipped when the row exists, so `.env.local` stays the source of truth.
//    The database is the shared one, so this is also the deployment's login:
//    `pnpm users` manages any other account.
{
  const { default: postgres } = await import('postgres')
  const { hashPassword } = await import('./hash-lib.mjs')
  const devEmail =
    read('LOCAL_DEV_EMAIL', env) ?? DEV_USER_DEFAULTS.LOCAL_DEV_EMAIL
  const devPassword =
    read('LOCAL_DEV_PASSWORD', env) ?? DEV_USER_DEFAULTS.LOCAL_DEV_PASSWORD

  const sql = postgres(
    read('DATABASE_URL_UNPOOLED', env) ?? read('DATABASE_URL', env),
  )
  try {
    const passwordHash = await hashPassword(devPassword)
    const [existing] = await sql`select id from users where email = ${devEmail}`
    if (existing) {
      await sql`update users set password_hash = ${passwordHash} where id = ${existing.id}`
      console.log(`database: ${devEmail} -- password synced from .env.local`)
    } else {
      await sql`insert into users (email, password_hash) values (${devEmail}, ${passwordHash})`
      console.log(`database: created ${devEmail} / ${devPassword}`)
    }
  } finally {
    await sql.end()
  }
}

// 6. The things that are actually yours: the provider keys. Ask for each one
//    that is missing rather than printing a warning and leaving you to find the
//    right place and var name. A key goes onto the Vercel project, for every
//    environment, so the deployment and the other Macs get it on their next
//    pull; a re-run only prompts for what is still absent.
const PROVIDER_KEYS = [
  {
    envVar: 'FAL_KEY',
    label: 'FAL',
    where: 'https://fal.ai/dashboard/keys',
    needed: 'image generation',
    consequence: 'the app runs, but image generation will fail',
  },
  {
    envVar: 'ANTHROPIC_API_KEY',
    label: 'Anthropic',
    where: 'https://console.anthropic.com/settings/keys',
    needed: 'the AI features layered on top of plain image generation',
    note: `Strongly recommended. Without it the app still runs and images still
generate, but Enhance Prompt, variation prompts, shot lists and Describe will
each tell you the key is missing instead of working.`,
    consequence:
      'image generation still works, but the AI-assisted features will report the missing key',
  },
]

for (const key of PROVIDER_KEYS) {
  const shellValue = process.env[key.envVar]
  let fileValue = read(key.envVar, readFileSync(ENV_LOCAL, 'utf8'))

  if (shellValue && shellValue !== fileValue) {
    // An exported value wins over .env.local -- dotenv does not overwrite
    // something already in process.env. A genuinely nasty trap: you paste a
    // fresh key, nothing changes, and it fails exactly as before. Prompting
    // here would be a lie, since whatever we wrote would still be shadowed.
    console.warn(
      `\n!! ${key.envVar} is exported in your shell (${shellValue.slice(0, 6)}...) and OVERRIDES .env.local.`,
    )
    console.warn(
      '   Editing .env.local will have no effect while that export exists.',
    )
    console.warn(
      '   Fix the exported value (check ~/.secrets.zsh), or unset it to let .env.local win.',
    )
    continue
  }

  if (fileValue) continue

  if (process.stdin.isTTY) {
    console.log(`
${key.label} key -- powers ${key.needed}.${key.note ? `\n${key.note}` : ''}
Get one at ${key.where} (leave blank to skip -- you can re-run
\`pnpm local:up\` later and it will ask again for whatever is still missing).`)
    const rl = createInterface({ input: process.stdin, output: process.stdout })
    const answer = (await rl.question(`\nPaste your ${key.label} key: `)).trim()
    rl.close()
    if (answer) {
      run('vercel', [
        'env',
        'add',
        key.envVar,
        '--environment',
        ENVIRONMENTS,
        '--sensitive',
        '--force',
        '--value',
        answer,
      ])
      writeFileSync(
        ENV_LOCAL,
        upsert(readFileSync(ENV_LOCAL, 'utf8'), key.envVar, answer),
      )
      fileValue = answer
      console.log(`${key.envVar} saved to the project and to .env.local`)
    }
  }

  if (!fileValue) {
    console.warn(`\nNo ${key.envVar} set -- ${key.consequence}.`)
    console.warn('Add one any time by re-running `pnpm local:up`.')
  }
}

console.log(`
Ready.
  app                      ${DEV_URL}
  sign in as               ${read('LOCAL_DEV_EMAIL', env) ?? DEV_USER_DEFAULTS.LOCAL_DEV_EMAIL} / ${read('LOCAL_DEV_PASSWORD', env) ?? DEV_USER_DEFAULTS.LOCAL_DEV_PASSWORD}
  database and images      the Vercel project's, shared with the deployment
`)

// 7. Hand back a running app rather than an instruction to start one. If a dev
//    server is already up on the port, don't start a second one -- just open it.
if (SKIP_DEV) {
  console.log('--no-dev: skipping the dev server. Start it with `pnpm dev`.')
} else if (await portInUse(DEV_PORT)) {
  // A TCP probe can't tell genzen's dev server from anything else on :3000, so
  // say which port is being reused rather than claiming it's ours.
  console.log(`Something is already serving :${DEV_PORT} -- opening it.`)
  openBrowser(DEV_URL)
} else {
  console.log('> starting dev server (ctrl-c to stop)\n')
  // Vite had a `--open` flag that launched the browser once it was listening.
  // Next does not, and passing it is a hard error, so poll the port instead --
  // which is what the flag was saving us from doing.
  const dev = spawn('pnpm', ['dev'], { cwd: ROOT, stdio: 'inherit' })

  void (async () => {
    for (let attempt = 0; attempt < 60; attempt++) {
      if (dev.exitCode !== null) return
      if (await portInUse(DEV_PORT)) {
        openBrowser(DEV_URL)
        return
      }
      await new Promise((resolve) => setTimeout(resolve, 500))
    }
    // 30s and still nothing listening: the server is having trouble and its own
    // output is the useful signal, so say nothing rather than open a dead tab.
  })()

  dev.on('exit', (code, signal) => {
    // Ctrl-C arrives as a signal, not a failure -- exiting 1 on it would be a lie.
    process.exit(signal ? 0 : (code ?? 0))
  })
}
